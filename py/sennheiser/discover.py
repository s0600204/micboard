    def __init__(self):
        self.sockets = []
        self.thread = threading.Thread(target=self.discover)

    def bind_listeners(self):
        for adapter in ifaddr.get_adapters():
            bound_ips = []
            for addr in adapter.ips:
                if not addr.is_IPv4 or self.is_ignored_address(addr.ip):
                    continue
                sock = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
                try:
                    sock.bind((addr.ip, self.MCAST_PORT))
                except OSError as error:
                    self.handle_binding_error(error, adapter, addr)
                else:
                    bound_ips.append(addr.ip)
                    self.sockets.append(sock)

            if bound_ips:
                logging.info(
                    "Discovering Sennheiser MCP devices via %s on '%s'", \
                    ', '.join(bound_ips), adapter.nice_name
                )

    def discover(self):
        self.bind_listeners()

        while True:
            sockets = self.sockets
            read_socks, write_socks, error_socks = select.select(sockets, sockets, sockets, .2)

            for tx in write_socks:
                tx.sendto(self.DISCOVERY_MSG, (self.MCAST_GRP, self.MCAST_PORT))

            for rx in read_socks:
                try:
                    data, (ip4_addr, _) = rx.recvfrom(1024)
                except Exception as e:
                    logging.error(e)
                else:
                    self.process_discovery_packet(ip4_addr, data)

            for sock in error_socks:
                logging.error("Errored: ", sock)

            time.sleep(self.SLEEP_LENGTH)

    def process_discovery_packet(self, ip4_addr, data):
        """
        data is expected in the following format:
        
            bytes  length  value
            -----  ------  ----------------------------------------
             0- 3       4  \x00%\x12\x06
             4-19      16  Model=<string, right-padded with spaces>
            20-37      18  ID=<string, right-padded with spaces>
            38- ?   11-19  IPA=<string, 7-15 chars long>
             ?-83   27-35  <null bytes>
            84          1  \x01

        We end up with (for example):

            response = {
                "Model": "EM300G3",
                "ID": "001B667A1234",
                "IPA": "192.168.1.100"
            }
        """
        response = {}
        for element in struct.unpack('4x16s18s19s28x', data):
            key, value = str(element, 'ascii').split('=')
            response[key] = value.strip(' \x00')

        model = WirelessMCPMic.MCP_MODEL_NAMES.get(response['Model'], False)
        if not model:
            logging.warning('Unrecognised MCP Model: %s', response['Model'])

        add_rx_to_dlist(ip4_addr, 'mcp_mic', model, 1)

    def start(self):
        self.thread.start()

    def stop(self):
        self.thread.join()
