    def __init__(self):
        self.socket = None
        self.thread = threading.Thread(target=self.discover)

        # Local addresses to not transmit the discovery message from.
        self.ignored_addrs = ['127.0.0.1']

    def discover(self):
        self.socket = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        self.socket.bind(('', self.MCAST_PORT))

        with selectors.DefaultSelector() as selector:
            selector.register(self.socket, selectors.EVENT_READ)
            while True:
                for adapter in ifaddr.get_adapters():
                    for addr in adapter.ips:
                        if not addr.is_IPv4 or addr.ip in self.ignored_addrs:
                            continue
                        with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as sock:
                            try:
                                sock.bind((addr.ip, self.MCAST_PORT + 1))
                            except OSError:
                                logging.debug(
                                    "Unable to send Sennheiser MCP discovery message via "\
                                    "%s on '%s'.", addr.ip, adapter.nice_name
                                    )
                                self.ignored_addrs.append(addr.ip)
                            else:
                                sock.sendto(self.DISCOVERY_MSG, (self.MCAST_GRP, self.MCAST_PORT))

                while selector.select(self.WAIT_TIMEOUT):
                    data, (ip4_addr, port) = self.socket.recvfrom(1024)
                    if port != self.MCAST_PORT:
                        continue
                    self.process_discovery_packet(ip4_addr, data)

    def process_discovery_packet(self, ip4_addr, data):
        """
        data is expected in the following format:
        
            bytes  length  value
            -----  ------  ----------------------------------------
             0- 3       4  \x00%\x12\x06
             4-19      16  Model=<string, right-padded with spaces>
            20-37      18  ID=<string, right-padded with spaces>
            38- ?   11-19  IPA=<string, 7-15 chars long>
             ?-83   27-35  <null bytes>
            84          1  \x01

        We end up with (for example):

            response = {
                "Model": "EM300G3",
                "ID": "001B667A1234",
                "IPA": "192.168.1.100"
            }
        """
        response = {}
        for element in struct.unpack('4x16s18s19s28x', data):
            key, value = str(element, 'ascii').split('=')
            response[key] = value.strip(' \x00')

        model = WirelessMCPMic.MCP_MODEL_NAMES.get(response['Model'], False)
        if not model:
            logging.warning('Unrecognised MCP Model: %s', response['Model'])

        add_rx_to_dlist(ip4_addr, 'mcp_mic', model, 1)

    def start(self):
        self.thread.start()

    def stop(self):
        self.thread.join()
